async function withFailureEnvelope(run, proof = diagnostic, write = text => process.stdout.write(text)) {
  const errors = [], retained = []; let entered = false;
  const emit = records => { retained.push(...records); };
  const record = (make, code) => {
    try { emit([make()]); } catch (error) { errors.push(error); emit([proof.boundary(code, error)]); }
  };
  try { await run({ entered: () => { entered = true; }, emit, record }); }
  catch (error) {
    errors.unshift(error);
    record(() => proof.record("outer", "none", entered ? "cleanup" : "setup", error), "REPORT_INVALID");
  } finally {
    try { proof.emit(retained, write); } catch (error) { errors.push(error); }
    try { proof.flush(write); } catch (error) { errors.push(error); }
  }
  if (errors.length === 1) throw errors[0];
  if (errors.length) throw new AggregateError(errors, "LiteLLM original and reporting failures");
}
