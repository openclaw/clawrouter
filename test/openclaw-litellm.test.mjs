async function withFailureEnvelope(run, proof = diagnostic, write = text => process.stdout.write(text)) {
  const errors = []; let entered = false;
  const emit = records => { try { proof.emit(records, write); } catch (error) { errors.push(error); } };
  try { await run({ entered: () => { entered = true; }, emit }); }
  catch (error) {
    errors.unshift(error);
    emit([proof.record("outer", "none", entered ? "cleanup" : "setup", error)]);
  }
  try { proof.flush(write); } catch (error) { errors.push(error); }
  if (errors.length === 1) throw errors[0];
  if (errors.length) throw new AggregateError(errors, "LiteLLM original and reporting failures");
}
